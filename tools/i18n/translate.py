def show_key_comparison():
    """显示源文件和目标文件的key对比"""
    print("\n🔍 Key对比分析")
    print("=" * 60)

    project_root, res_dir, source_file = setup_paths()
    source_strings = load_strings(source_file)

    print(f"源文件key总数: {len(source_strings)}")

    for lang_name, folder in TARGET_LANGS.items():
        target_file = os.path.join(res_dir, folder, "strings.xml")
        existing_strings = load_strings(target_file)

        # 找出交集和差集
        source_keys = set(source_strings.keys())
        existing_keys = set(existing_strings.keys())

        common_keys = source_keys & existing_keys  # 都有的key
        missing_keys = source_keys - existing_keys  # 源有目标无
        extra_keys = existing_keys - source_keys    # 目标有源无（多余的）

        print(f"\n{lang_name} ({folder}):")
        print(f"  已有key: {len(existing_keys)}个")
        print(f"  共同key: {len(common_keys)}个（跳过不翻译）")
        print(f"  缺失key: {len(missing_keys)}个（需要翻译）")

        if extra_keys:
            print(f"  多余key: {len(extra_keys)}个（目标文件中有但源文件中没有）")
            for key in list(extra_keys)[:3]:
                print(f"    - {key}")

